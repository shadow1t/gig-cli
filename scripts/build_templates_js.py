"""Generate web/templates.js from gig/templates/*.gitignore.

Run after changing bundled templates:
    python scripts/build_templates_js.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES_DIR = ROOT / "gig" / "templates"
OUT = ROOT / "web" / "templates.js"

ALIASES = {
    "py": "python", "python3": "python", "js": "node", "ts": "node",
    "nodejs": "node", "golang": "go", "c++": "cpp", "cplusplus": "cpp",
    "c#": "csharp", "cs": "csharp", "rb": "ruby", "kt": "kotlin",
    "mac": "macos", "win": "windows", "vsc": "vscode", "idea": "jetbrains",
    "flutter": "dart", "tex": "latex",
}


def main() -> None:
    templates = {}
    for file in sorted(TEMPLATES_DIR.glob("*.gitignore")):
        name = file.name[: -len(".gitignore")].lower()
        templates[name] = file.read_text(encoding="utf-8")
    OUT.parent.mkdir(exist_ok=True)
    payload = {
        "templates": templates,
        "aliases": ALIASES,
        "generated_from": "gig/templates/*.gitignore",
    }
    OUT.write_text(
        "// Auto-generated by scripts/build_templates_js.py - do not edit manually.\n"
        "const GIG_DATA = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} with {len(templates)} templates")


if __name__ == "__main__":
    main()
