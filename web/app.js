/* gig-cli web UI - mirrors gig/core.py generate() logic */
(function () {
  "use strict";

  var templates = GIG_DATA.templates;
  var aliases = GIG_DATA.aliases;
  var names = Object.keys(templates).sort();

  var listEl = document.getElementById("template-list");
  var searchEl = document.getElementById("search");
  var previewEl = document.getElementById("preview");
  var selectedCountEl = document.getElementById("selected-count");
  var copyStatusEl = document.getElementById("copy-status");
  var selected = new Set();

  document.getElementById("tpl-count").textContent = names.length;

  function resolveName(name) {
    name = name.trim().toLowerCase();
    return aliases[name] || name;
  }

  function isSectionHeader(line) {
    return /^#\s*={3,}.*={3,}\s*$/.test(line);
  }

  function generate(langs) {
    var out = ["# Generated by gig-cli (https://github.com/shadow1t/gig-cli)", ""];
    var seen = new Set();
    var resolved = [];
    langs.forEach(function (lang) {
      var name = resolveName(lang);
      if (templates[name] && resolved.indexOf(name) === -1) resolved.push(name);
    });
    resolved.forEach(function (name) {
      out.push("# ===== " + name + " =====");
      templates[name].split("\n").forEach(function (raw) {
        var line = raw.replace(/\s+$/, "");
        var key = line.trim();
        if (key && !isSectionHeader(key) && seen.has(key)) return;
        if (key) seen.add(key);
        out.push(line);
      });
      out.push("");
    });
    return out.join("\n").replace(/\s+$/, "") + "\n";
  }

  function renderList(filter) {
    listEl.innerHTML = "";
    var f = (filter || "").trim().toLowerCase();
    var shown = 0;
    names.forEach(function (name) {
      if (f && name.indexOf(f) === -1 && !(aliases[name] && aliases[name].indexOf(f) !== -1)) {
        var aliasHit = Object.keys(aliases).some(function (a) {
          return a.indexOf(f) !== -1 && aliases[a] === name;
        });
        if (!aliasHit) return;
      }
      shown++;
      var li = document.createElement("li");
      var label = document.createElement("label");
      var cb = document.createElement("input");
      cb.type = "checkbox";
      cb.checked = selected.has(name);
      cb.addEventListener("change", function () {
        if (cb.checked) selected.add(name);
        else selected.delete(name);
        update();
      });
      label.appendChild(cb);
      label.appendChild(document.createTextNode(name));
      li.appendChild(label);
      listEl.appendChild(li);
    });
    if (!shown) {
      var li = document.createElement("li");
      li.className = "muted";
      li.textContent = "no templates matching '" + filter + "'";
      listEl.appendChild(li);
    }
  }

  function update() {
    var langs = Array.from(selected);
    previewEl.textContent = generate(langs);
    selectedCountEl.textContent = langs.length + " selected";
    syncHash(langs);
  }

  function syncHash(langs) {
    var h = langs.map(resolveName).join(",");
    history.replaceState(null, "", h ? "#" + encodeURIComponent(h) : location.pathname);
  }

  function loadFromHash() {
    var h = decodeURIComponent(location.hash.replace(/^#/, ""));
    if (!h) return;
    h.split(",").forEach(function (p) {
      var name = resolveName(p);
      if (templates[name]) selected.add(name);
    });
  }

  searchEl.addEventListener("input", function () {
    renderList(searchEl.value);
  });

  document.getElementById("select-all").addEventListener("click", function () {
    var f = searchEl.value.trim().toLowerCase();
    names.forEach(function (name) {
      if (!f || name.indexOf(f) !== -1) selected.add(name);
    });
    renderList(searchEl.value);
    update();
  });

  document.getElementById("clear-all").addEventListener("click", function () {
    selected.clear();
    renderList(searchEl.value);
    update();
  });

  document.getElementById("copy-btn").addEventListener("click", function () {
    var text = previewEl.textContent;
    navigator.clipboard.writeText(text).then(function () {
      copyStatusEl.textContent = "copied!";
      setTimeout(function () { copyStatusEl.textContent = ""; }, 1500);
    });
  });

  document.getElementById("download-btn").addEventListener("click", function () {
    var blob = new Blob([previewEl.textContent], { type: "text/plain" });
    var a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = ".gitignore";
    a.click();
    URL.revokeObjectURL(a.href);
  });

  document.getElementById("share-btn").addEventListener("click", function () {
    navigator.clipboard.writeText(location.href).then(function () {
      copyStatusEl.textContent = "share link copied!";
      setTimeout(function () { copyStatusEl.textContent = ""; }, 1500);
    });
  });

  var themeToggle = document.getElementById("theme-toggle");
  if (localStorage.getItem("gig-theme") === "dark") {
    document.body.classList.add("dark");
    themeToggle.textContent = "☀️";
  }
  themeToggle.addEventListener("click", function () {
    document.body.classList.toggle("dark");
    var dark = document.body.classList.contains("dark");
    localStorage.setItem("gig-theme", dark ? "dark" : "light");
    themeToggle.textContent = dark ? "☀️" : "🌙";
  });

  loadFromHash();
  renderList("");
  update();

  if (typeof module !== "undefined" && module.exports) {
    module.exports = { generate: generate, resolveName: resolveName };
  }
})();
