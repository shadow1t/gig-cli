import re
from pathlib import Path

BUNDLED_TEMPLATES_DIR = Path(__file__).resolve().parent / "templates"
USER_TEMPLATES_DIR = Path.home() / ".gig-cli" / "templates"

NAME_NORMALIZATION = {
    "c++": "cpp",
    "c#": "csharp",
    "f#": "fsharp",
    "objective-c": "objectivec",
}

ALIASES = {
    "py": "python",
    "python3": "python",
    "js": "node",
    "ts": "node",
    "nodejs": "node",
    "golang": "go",
    "c++": "cpp",
    "cplusplus": "cpp",
    "c#": "csharp",
    "cs": "csharp",
    "rb": "ruby",
    "kt": "kotlin",
    "mac": "macos",
    "win": "windows",
    "vscode": "vscode",
    "vsc": "vscode",
    "idea": "jetbrains",
    "flutter": "dart",
    "latex": "latex",
    "tex": "latex",
}

SECTION_HEADER = re.compile(r"^#\s*={3,}.*={3,}\s*$")


def _strip_name(filename: str) -> str:
    return filename[: -len(".gitignore")] if filename.endswith(".gitignore") else filename


def _normalize_name(name: str) -> str:
    name = name.strip().lower()
    return NAME_NORMALIZATION.get(name, name)


def available_templates() -> dict:
    """Return {name: content} for bundled + user templates. User templates override bundled."""
    templates = {}
    for directory in (BUNDLED_TEMPLATES_DIR, USER_TEMPLATES_DIR):
        if not directory.is_dir():
            continue
        for file in sorted(directory.glob("*.gitignore")):
            name = _normalize_name(_strip_name(file.name))
            templates[name] = file.read_text(encoding="utf-8")
    return templates


def resolve_name(name: str) -> str:
    name = name.strip().lower()
    return ALIASES.get(name, name)


def search_templates(term: str) -> list:
    term = term.strip().lower()
    if not term:
        return []
    matches = []
    for name in available_templates():
        if term in name:
            matches.append(name)
    for alias, target in ALIASES.items():
        if term in alias and target not in matches:
            matches.append(f"{alias} -> {target}")
    return sorted(matches)


def _dedup_lines(lines: list, seen: set = None) -> list:
    if seen is None:
        seen = set()
    out = []
    for raw in lines:
        line = raw.rstrip()
        key = line.strip()
        if key and not SECTION_HEADER.match(key) and key in seen:
            continue
        if key:
            seen.add(key)
        out.append(line)
    return out


def generate(langs: list) -> str:
    """Combine multiple language templates into one deduplicated .gitignore content."""
    templates = available_templates()
    resolved = []
    missing = []
    for lang in langs:
        name = resolve_name(lang)
        if name in templates:
            if name not in resolved:
                resolved.append(name)
        else:
            missing.append(lang)
    if missing:
        raise KeyError(missing)

    out = ["# Generated by gig-cli (https://github.com/shadow1t/gig-cli)", ""]
    seen = set()
    for name in resolved:
        out.append(f"# ===== {name} =====")
        out.extend(_dedup_lines(templates[name].splitlines(), seen))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def default_output_path() -> Path:
    return Path.cwd() / ".gitignore"


def write_gitignore(content: str, path: Path = None, append: bool = False) -> Path:
    path = path or default_output_path()
    if append and path.exists():
        existing = path.read_text(encoding="utf-8")
        if not existing.endswith("\n"):
            existing += "\n"
        path.write_text(existing + "\n" + content, encoding="utf-8")
    else:
        path.write_text(content, encoding="utf-8")
    return path
